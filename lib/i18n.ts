export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, ar };

/**
 * Arabic-Indic digits inside a Latin run still carry a right-to-left bidi class, so "٪٩" of a
 * replacement renders with the percent sign on the wrong side. Isolating each run keeps the digits
 * and the surrounding Latin text in their own order in either direction.
 */
const BIDI_ISOLATE = /[\u2066-\u2069]/g;

export const tx = (lang: Lang, key: StringKey): string => {
    const text = STRINGS[isLang(lang) ? lang : 'en']?.[key] ?? STRINGS.en[key] ?? key;
    return text.replace(BIDI_ISOLATE, '');
};

